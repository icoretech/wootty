#!/usr/bin/env node

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(scriptDir, "..");

function readJson(path) {
  return JSON.parse(readFileSync(path, "utf8"));
}

function toUpperSnake(input) {
  return input.replace(/[^a-zA-Z0-9]+/g, "_").toUpperCase();
}

function toPascalCase(input) {
  return input
    .split(/[^a-zA-Z0-9]+/)
    .filter(Boolean)
    .map((part) => `${part.charAt(0).toUpperCase()}${part.slice(1)}`)
    .join("");
}

function tsString(value) {
  return JSON.stringify(value);
}

function renderTsStringArray(values, indent = "  ") {
  if (values.length === 0) {
    return "[]";
  }
  return `[\n${values.map((value) => `${indent}${tsString(value)}`).join(",\n")}\n]`;
}

function renderGoStringArray(values, indent = "\t") {
  if (values.length === 0) {
    return "{}";
  }
  return `{\n${values.map((value) => `${indent}${JSON.stringify(value)},`).join("\n")}\n}`;
}

const terminalContract = readJson(
  resolve(repoRoot, "contracts/terminal-wire-contract.json"),
);
const sessionsContract = readJson(
  resolve(repoRoot, "contracts/sessions-contract.json"),
);
const routesContract = readJson(resolve(repoRoot, "contracts/http-routes.json"));

const clientTypeEntries = terminalContract.client_messages.types.map((type) => {
  return `  ${toUpperSnake(type)}: ${tsString(type)}`;
});
const serverTypeEntries = terminalContract.server_messages.types.map((type) => {
  return `  ${toUpperSnake(type)}: ${tsString(type)}`;
});
const serverCodeEntries = terminalContract.server_errors.known_codes.map(
  (code) => {
    return `  ${toUpperSnake(code)}: ${tsString(code)}`;
  },
);

const tsOutput = `// Code generated by scripts/generate-terminal-contract-bindings.mjs. DO NOT EDIT.

export const TERMINAL_WIRE_CONTRACT_VERSION = ${terminalContract.version} as const;

export const TERMINAL_DIMENSION_LIMIT = {
  MIN: ${terminalContract.dimension.min},
  MAX: ${terminalContract.dimension.max},
} as const;

export const TERMINAL_BACKEND_ROUTE = {
  SESSIONS_HTTP: ${tsString(routesContract.sessions_http)},
  TERMINAL_WS: ${tsString(routesContract.terminal_ws)},
} as const;

export const TERMINAL_CLIENT_MESSAGE_TYPE = {
${clientTypeEntries.join(",\n")},
} as const;

export const TERMINAL_SERVER_MESSAGE_TYPE = {
${serverTypeEntries.join(",\n")},
} as const;

export const TERMINAL_SERVER_ERROR_CODE = {
${serverCodeEntries.join(",\n")},
} as const;

export const TERMINAL_SERVER_ERROR_CODES = ${renderTsStringArray(
  terminalContract.server_errors.known_codes,
)} as const;

export const TERMINAL_UNKNOWN_SERVER_ERROR_POLICY = ${tsString(
  terminalContract.server_errors.unknown_code_policy,
)} as const;

export const SESSIONS_ENVELOPE_FIELD = ${tsString(
  sessionsContract.envelope_field,
)} as const;

export const SESSION_SNAPSHOT_REQUIRED_FIELDS = ${renderTsStringArray(
  sessionsContract.snapshot.required,
)} as const;

export const SESSION_SNAPSHOT_OPTIONAL_FIELDS = ${renderTsStringArray(
  sessionsContract.snapshot.optional,
)} as const;
`;

const goClientTypeConstants = terminalContract.client_messages.types
  .map((type) => {
    return `\tClientMessageType${toPascalCase(type)} = ${JSON.stringify(type)}`;
  })
  .join("\n");

const goServerTypeConstants = terminalContract.server_messages.types
  .map((type) => {
    return `\tServerMessageType${toPascalCase(type)} = ${JSON.stringify(type)}`;
  })
  .join("\n");

const goServerErrorConstants = terminalContract.server_errors.known_codes
  .map((code) => {
    return `\tServerErrorCode${toPascalCase(code)} = ${JSON.stringify(code)}`;
  })
  .join("\n");

const goOutput = `// Code generated by scripts/generate-terminal-contract-bindings.mjs. DO NOT EDIT.

package protocol

const (
\tWireContractVersion = ${terminalContract.version}
\tMinDimension        = ${terminalContract.dimension.min}
\tMaxDimension        = ${terminalContract.dimension.max}
)

const (
\tSessionsHTTPRoute = ${JSON.stringify(routesContract.sessions_http)}
\tTerminalWSRoute   = ${JSON.stringify(routesContract.terminal_ws)}
)

const (
${goClientTypeConstants}
)

const (
${goServerTypeConstants}
)

const (
${goServerErrorConstants}
)

const UnknownServerErrorCodePolicy = ${JSON.stringify(
  terminalContract.server_errors.unknown_code_policy,
)}

var ClientMessageTypes = []string${renderGoStringArray(
  terminalContract.client_messages.types,
)}

var ServerMessageTypes = []string${renderGoStringArray(
  terminalContract.server_messages.types,
)}

var KnownServerErrorCodes = []string${renderGoStringArray(
  terminalContract.server_errors.known_codes,
)}

const SessionsEnvelopeField = ${JSON.stringify(sessionsContract.envelope_field)}

var SessionSnapshotRequiredFields = []string${renderGoStringArray(
  sessionsContract.snapshot.required,
)}

var SessionSnapshotOptionalFields = []string${renderGoStringArray(
  sessionsContract.snapshot.optional,
)}
`;

writeFileSync(
  resolve(
    repoRoot,
    "apps/web/src/features/terminal/protocol/generated-wire-contract.ts",
  ),
  tsOutput,
  "utf8",
);
writeFileSync(
  resolve(repoRoot, "apps/server/internal/protocol/wire_contract.go"),
  goOutput,
  "utf8",
);

console.log("Generated terminal contract bindings for web and server.");
